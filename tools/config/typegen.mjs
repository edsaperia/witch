// Derives the tuning data's static type from the schema; validation stays in schema.mjs --check and tuningSchema.test.ts.
//   node tools/config/typegen.mjs --write
//   node tools/config/typegen.mjs --check
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export function schemaType(schema, source = 'typeof raw', depth = 0) {
  let type;
  if (schema.enum) type = schema.enum.map(v => JSON.stringify(v)).join(' | ') || 'never';
  else if (schema.type === 'array') type = `Array<${schema.items ? schemaType(schema.items, `${source}[number]`, depth) : `${source}[number]`}>`;
  else if (schema.type === 'object') {
    const pad = '  '.repeat(depth), props = Object.entries(schema.properties ?? {}).map(([key, s]) =>
      `${pad}  ${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${schemaType(s, `${source}[${JSON.stringify(key)}]`, depth + 1)};`);
    if (schema.additionalProperties && typeof schema.additionalProperties === 'object') props.push(`${pad}  [key: string]: ${schemaType(schema.additionalProperties, `${source}[string]`, depth + 1)};`);
    type = props.length ? `{\n${props.join('\n')}\n${pad}}` : 'Record<string, unknown>';
  } else type = schema.type ?? source; // Empty/mixed schemas impose no additional constraint; retain JSON's inferred type.
  return schema.nullable ? `(${type}) | null` : type;
}

export function declaration(schema) {
  return '// Generated by node tools/config/typegen.mjs --write; edit config/schema/tuning.schema.json instead.\n' +
    'import type raw from "../../config/tuning.json";\nexport type SchemaTuning = ' + schemaType(schema) + ';\n';
}

export function main(args = process.argv.slice(2)) {
  if (args.length !== 1 || !['--write', '--check'].includes(args[0])) throw Error('Use --write or --check');
  const file = 'src/rules/tuning.generated.d.ts', want = declaration(JSON.parse(readFileSync('config/schema/tuning.schema.json', 'utf8')));
  if (args[0] === '--write') writeFileSync(file, want);
  else if (!existsSync(file) || readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== want) {
    console.error(`${file}: stale; fix: node tools/config/typegen.mjs --write`); process.exitCode = 1;
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
