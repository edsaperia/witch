// Bundles the vocal-tract voice's AudioWorklet (worklet.js with the vendored Pink Trombone) into
// src/platform/audio/tract/tractModule.ts as one string the game loads as a Blob URL: node tools/voice/tract/build.mjs.
// Committed, like the FOF voice's compiled module; run it again after any change to the worklet or the vendored library.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url)), root = resolve(here, "../../..");
const r = await build({ entryPoints: [resolve(here, "worklet.js")], bundle: true, format: "iife", target: "es2022", minify: true, write: false, logLevel: "warning" });
const code = r.outputFiles[0].text;
const out = resolve(root, "src/platform/audio/tract/tractModule.ts");
writeFileSync(out, `// Generated by tools/voice/tract/build.mjs from tools/voice/tract/worklet.js and tools/voice/pink-trombone (Neil Thapen's\n// Pink Trombone, MIT, as a library by Gorka Egino; the noise by Stefan Gustavson, public domain): the vocal-tract voice's\n// AudioWorklet as one script. Never edit by hand.\nexport const TRACT_SOURCE = ${JSON.stringify(code)};\n`);
console.log(`wrote ${out} (${(code.length / 1024).toFixed(1)} KB)`);
