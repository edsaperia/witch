// Compiles Witch's FOF singing voice (tools/voice/fof/fof.dsp: Mike Olsen's pm.SFFormantModelFofSmooth from Faust's
// physmodels.lib; Ed, 2026-10-11) to WebAssembly with the Faust compiler (@grame/faustwasm, npm, installed into a temporary
// folder: the game never ships it, nor its runtime) and writes src/platform/audio/fof/fofModule.ts: the module as base64,
// one voice's memory size, its outputs and its parameters' offsets. The compiled code is ours to license: physmodels.lib
// and the rest of the Faust libraries are LGPL with GRAME's exception for code the Faust compiler generates from them
// ("you may ... distribute the compiled code generated by the FAUST compiler ... under your own copyright and license").
// Our own worklet runs it (src/platform/audio/fof/fof.ts). Needs the network (npm) the first time.
//   node tools/voice/fof/build.mjs
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const FAUSTWASM = "0.19.0";
const here = dirname(fileURLToPath(import.meta.url)), root = resolve(here, "../..", "..");
const work = join(tmpdir(), `witch-faustwasm-${FAUSTWASM}`), out = join(work, "out");
if (!existsSync(join(work, "node_modules/@grame/faustwasm"))) {
  mkdirSync(work, { recursive: true });
  execFileSync("npm", ["install", "--prefix", work, "--no-save", "--silent", `@grame/faustwasm@${FAUSTWASM}`], { stdio: "inherit" });
}
execFileSync("node", [join(work, "node_modules/@grame/faustwasm/scripts/faust2wasm.js"), join(here, "fof.dsp"), out, "-poly", "-no-template"], { stdio: "inherit" });
const wasm = readFileSync(join(out, "dsp-module.wasm")), meta = JSON.parse(readFileSync(join(out, "dsp-meta.json"), "utf8"));
const params = {};
const walk = items => { for (const x of items) { if (x.items) walk(x.items); else if (x.index !== undefined) params[x.address.split("/").pop()] = x.index; } };
walk(meta.ui);
const code = `// Written by tools/voice/fof/build.mjs from tools/voice/fof/fof.dsp: never edit by hand. Faust ${meta.version} (@grame/faustwasm ${FAUSTWASM}).
// Mike Olsen's pm.SFFormantModelFofSmooth (Faust's physmodels.lib), compiled: the Faust libraries are LGPL with GRAME's exception
// for the code the Faust compiler generates, which may be distributed under any licence (Witch's).
/** The compiled voice (WebAssembly, base64). */
export const FOF_WASM = "${wasm.toString("base64")}";
/** One voice's memory (bytes), its outputs, and its parameters' offsets in it. */
export const FOF_META = ${JSON.stringify({ size: meta.size, outputs: meta.outputs, params })};
`;
writeFileSync(join(root, "src/platform/audio/fof/fofModule.ts"), code);
console.log(`wrote src/platform/audio/fof/fofModule.ts (${(code.length / 1024).toFixed(1)} KB; one voice ${meta.size} bytes; params ${Object.keys(params).join(", ")})`);
